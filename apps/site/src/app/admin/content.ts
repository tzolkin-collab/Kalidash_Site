export function parseContent(raw: string | null): MotionContent {
  try {
    const value = JSON.parse(raw || "null");
    if (!value || typeof value !== "object") return structuredClone(initialContent);
    return { ...initialContent, ...value };
  } catch {
    return structuredClone(initialContent);
  }
}

export function safeLink(value: string) {
  return /^(#[\w-]+|\/(?!\/)|https:\/\/)/.test(value) ? value : "#diagnostico";
}
